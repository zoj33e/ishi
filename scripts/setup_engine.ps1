<#
.SYNOPSIS
  Download KataGo + networks, run the benchmark, write engine/analysis.cfg and the repo-root .env.

.DESCRIPTION
  Everything lands in <repo>/engine (git-ignored). Safe to re-run: existing downloads are reused,
  and existing .env entries other than ISHI_KATAGO_* (e.g. ANTHROPIC_API_KEY) are kept.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\setup_engine.ps1
  powershell -ExecutionPolicy Bypass -File scripts\setup_engine.ps1 -SkipBenchmark
#>
param(
    # v1.18.2 ships no OpenCL Windows build; 1.18.1 is the newest one that does (see D-015).
    [string]$KataGoVersion = "1.18.1",
    [ValidateSet("opencl")] [string]$Backend = "opencl",
    [string]$MainNet = "kata1-b18c384nbt-s9996604416-d4316597426.bin.gz",
    [string]$HumanNet = "b18c384nbt-humanv0.bin.gz",
    [int]$NumAnalysisThreads = 4,
    [switch]$SkipBenchmark
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$Root = Split-Path -Parent $PSScriptRoot
$EngineDir = Join-Path $Root "engine"
$KataDir = Join-Path $EngineDir "katago"
$ModelDir = Join-Path $EngineDir "models"
$CfgPath = Join-Path $EngineDir "analysis.cfg"
$EnvPath = Join-Path $Root ".env"
New-Item -ItemType Directory -Force $KataDir, $ModelDir | Out-Null

function Get-File([string]$Url, [string]$Dest) {
    if (Test-Path $Dest) { Write-Host "  have $(Split-Path -Leaf $Dest)"; return }
    Write-Host "  downloading $Url"
    $tmp = "$Dest.part"
    & curl.exe -L --fail --retry 3 -o $tmp $Url
    if ($LASTEXITCODE -ne 0) { throw "download failed: $Url" }
    Move-Item -Force $tmp $Dest
}

# 1. KataGo binary ---------------------------------------------------------------------------
Write-Host "[1/4] KataGo v$KataGoVersion ($Backend)"
$zipName = "katago-v$KataGoVersion-$Backend-windows-x64.zip"
$zipPath = Join-Path $EngineDir $zipName
Get-File "https://github.com/lightvector/KataGo/releases/download/v$KataGoVersion/$zipName" $zipPath
$KataExe = Join-Path $KataDir "katago.exe"
if (-not (Test-Path $KataExe)) {
    Expand-Archive -Force $zipPath $KataDir
    $found = Get-ChildItem $KataDir -Recurse -Filter katago.exe | Select-Object -First 1
    if (-not $found) { throw "katago.exe not found in $zipName" }
    if ($found.DirectoryName -ne $KataDir) {
        Get-ChildItem $found.DirectoryName | Move-Item -Destination $KataDir -Force
    }
}
& $KataExe version

# 2. Networks --------------------------------------------------------------------------------
Write-Host "[2/4] Networks"
$MainPath = Join-Path $ModelDir $MainNet
$HumanPath = Join-Path $ModelDir $HumanNet
Get-File "https://media.katagotraining.org/uploaded/networks/models/kata1/$MainNet" $MainPath
Get-File "https://github.com/lightvector/KataGo/releases/download/v1.15.0/$HumanNet" $HumanPath

# 3. Benchmark -------------------------------------------------------------------------------
# The first OpenCL run also tunes kernels for this GPU (cached next to katago.exe).
$threads = 8
if (-not $SkipBenchmark) {
    Write-Host "[3/4] Benchmark (first OpenCL run tunes kernels; may take a few minutes)"
    $benchCfg = Join-Path $EngineDir "benchmark.cfg"
    @(
        "logDir = $($EngineDir -replace '\\','/')/logs"
        "nnMaxBatchSize = 64"
        "nnCacheSizePowerOfTwo = 20"
        "numSearchThreads = 8"  # required key; the benchmark overrides it with each -t value
    ) | Set-Content -Encoding ascii $benchCfg
    # KataGo logs to stderr; in Windows PowerShell 5.1 that becomes an error record under "Stop".
    $ErrorActionPreference = "Continue"
    $out = & $KataExe benchmark -model $MainPath -config $benchCfg -v 400 -t "2,4,6,8,12,16" 2>&1 |
        ForEach-Object { "$_" }
    $benchExit = $LASTEXITCODE
    $ErrorActionPreference = "Stop"
    $out | Set-Content -Encoding utf8 (Join-Path $EngineDir "benchmark.log")
    if ($benchExit -ne 0) { throw "benchmark failed (exit $benchExit); see engine/benchmark.log" }
    $rec = $out | Select-String -Pattern "numSearchThreads\s*=\s*(\d+).*recommended" | Select-Object -Last 1
    if ($rec) {
        $threads = [int]$rec.Matches[0].Groups[1].Value
        Write-Host "  benchmark recommends numSearchThreads = $threads"
    } else {
        Write-Warning "could not parse benchmark recommendation; using $threads (see engine/benchmark.log)"
    }
} else {
    Write-Host "[3/4] Benchmark skipped; numSearchThreadsPerAnalysisThread = $threads"
}

# 4. analysis.cfg + .env ---------------------------------------------------------------------
Write-Host "[4/4] Writing $CfgPath and $EnvPath"
$batch = [Math]::Max(64, $NumAnalysisThreads * $threads)
@(
    "# Generated by scripts/setup_engine.ps1 - re-run it instead of editing by hand."
    "logDir = $($EngineDir -replace '\\','/')/logs"
    "logErrorsAndWarnings = true"
    "warnUnusedFields = true"
    "reportAnalysisWinratesAs = BLACK"
    "maxVisits = 500"
    "numAnalysisThreads = $NumAnalysisThreads"
    "numSearchThreadsPerAnalysisThread = $threads"
    "nnMaxBatchSize = $batch"
    "nnCacheSizePowerOfTwo = 22"
    "nnMutexPoolSizePowerOfTwo = 17"
    "nnRandomize = true"
) | Set-Content -Encoding ascii $CfgPath

$vars = [ordered]@{
    "ISHI_KATAGO_BIN"         = $KataExe
    "ISHI_KATAGO_MODEL"       = $MainPath
    "ISHI_KATAGO_HUMAN_MODEL" = $HumanPath
    "ISHI_KATAGO_CONFIG"      = $CfgPath
}
$kept = @()
if (Test-Path $EnvPath) {
    $kept = Get-Content $EnvPath | Where-Object { $_ -notmatch '^\s*ISHI_KATAGO_' }
}
$lines = @($kept) + ($vars.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" })
[IO.File]::WriteAllLines($EnvPath, [string[]]$lines)  # UTF-8 without BOM

Write-Host "Done. Start the app with: powershell -ExecutionPolicy Bypass -File scripts\start.ps1"
